/* Dependency-free source invariants for FCGS Gate Command UTC clock fix.
 * For real PostgreSQL evaluation also run test-access-control-command-clock.sql.
 */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const clock = read('server/access-control-command-clock.ts');
const routes = read('server/access-control-routes.ts');
const ops = read('server/access-control-operations.ts');
let count = 0;
function test(name, fn) { fn(); count += 1; console.log(`PASS ${name}`); }

test('UTC database clock independent from PostgreSQL session timezone', () => {
  assert.match(clock, /CURRENT_TIMESTAMP AT TIME ZONE 'UTC'/);
});
test('TTL generated by database with a validated positive millisecond duration', () => {
  assert.match(clock, /Number\.isSafeInteger\(milliseconds\)/);
  assert.match(clock, /INTERVAL '1 millisecond'/);
});
test('No JS Date injected as the lease-expiry scheduler SQL comparison', () => {
  assert.doesNotMatch(ops, /leaseExpiresAt\}\s*<\s*\$\{now\}/);
  assert.doesNotMatch(ops, /claimedAt\}\s*<\s*\$\{staleProcessingBefore\}/);
  assert.match(ops, /leaseExpiresAt\}\s*<\s*\$\{GATE_UTC_NOW\}/);
  assert.match(ops, /claimedAt\}\s*<\s*\$\{GATE_UTC_NOW\}\s*-\s*INTERVAL '20 minutes'/);
});
test('Command TTLs for identity, manual-open and tests use database UTC', () => {
  assert.match(ops, /expiresAt:\s*gateUtcDeadlineAfterMs\(ttlMs\)/);
  assert.match(routes, /expiresAt:\s*gateUtcDeadlineAfterMs\(OPEN_COMMAND_TTL_MS\)/);
  assert.equal((routes.match(/expiresAt:\s*gateUtcDeadlineAfterMs\(TEST_COMMAND_TTL_MS\)/g) || []).length, 2);
  assert.doesNotMatch(routes, /expiresAt:\s*new Date\(Date\.now\(\)\s*\+/);
});
test('Bridge claims use UTC for eligibility, lease start and end', () => {
  assert.match(routes, /c\.expires_at\s*>\s*\$\{GATE_UTC_NOW\}/);
  assert.match(routes, /first\.expires_at\s*>\s*\$\{GATE_UTC_NOW\}/);
  assert.match(routes, /claimed_at=\$\{GATE_UTC_NOW\}/);
  assert.match(routes, /lease_expires_at=\$\{GATE_UTC_NOW\}\+INTERVAL '90 seconds'/);
});
test('Bridge response explicitly converts stored UTC timestamp to timestamptz', () => {
  assert.match(routes, /c\.expires_at AT TIME ZONE 'UTC'\) AS expires_at/);
});
test('Lease renewal remains claim-token and bridge guarded', () => {
  assert.match(routes, /UPDATE gate_commands SET lease_expires_at=\$\{GATE_UTC_NOW\}\+INTERVAL '90 seconds' WHERE id=\$\{Number\(req\.params\.id\)\} AND bridge_id=\$\{bridge\.id\} AND status='processing' AND claim_token=\$\{token\}/);
});
test('Acknowledgements are compare-and-set and rejected after uncertain transition', () => {
  assert.match(routes, /const completed = await db\.update\(gateCommands\)/);
  assert.match(routes, /eq\(gateCommands\.status, "processing"\)/);
  assert.match(routes, /command\.claimToken \? eq\(gateCommands\.claimToken, input\.claimToken!\)/);
  assert.match(routes, /if \(!completed\.length\)/);
});
test('Existing command timeout and physical-open safeguards remain unchanged', () => {
  assert.match(routes, /OPEN_COMMAND_TTL_MS = 15_000/);
  assert.match(routes, /TEST_COMMAND_TTL_MS = 60_000/);
  assert.match(ops, /IDENTITY_COMMAND_TTL_MS = 7 \* 24 \* 60 \* 60 \* 1000/);
  assert.match(routes, /FOR UPDATE OF c SKIP LOCKED/);
  assert.match(routes, /NOT EXISTS \(SELECT 1 FROM gate_commands active WHERE active\.device_id=c\.device_id AND active\.status='processing'\)/);
  assert.doesNotMatch(ops, /status: "pending"[^;]*commandType: "open_gate"/s);
});
console.log(`${count} source invariants passed. Run SQL test for real PostgreSQL timing verification; no hardware has been exercised.`);
